/**
 * Відомі перевищення, у CSS px — стеля на кожен маршрут, і вона лише спадає.
 *
 * Число, а не перелік елементів: тут наслідок ОДИН на сторінку
 * (`scrollWidth` документа), і саме він або є, або ні. Перелік елементів
 * доречний там, де порушень багато й вони різні (`TOUCH_DEBT`); стеля в
 * пікселях доречна там, де порушення одне й міряється числом.
 *
 * `/test` — 330 px: довге слово в заголовку `.g-block__title` чернетки
 * галерей (заміряно 2026-09-10: `scrollWidth` 292 при `clientWidth` 250).
 * Чому борг, а не правка — та сама причина, що вже записана для `/test` у
 * `touch-baseline.ts`: сторінки немає ні в індексі, ні в меню, а
 * `test/+page.svelte` стоїть у `SIZE_DEBT` на 1280 SLOC проти межі 400, тобто
 * рости йому не можна. Дописати туди стилі означало б розміняти зафіксований
 * борг розміру на причісування чернетки.
 *
 * Відсутність маршруту в мапі — теж твердження: «тут перевищень немає».
 */
export const REFLOW_DEBT: Record<string, number> = {
	'/test': 330
};
