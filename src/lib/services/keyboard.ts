/**
 * Захисти обробника гарячих клавіш (HOTKEYS-v8 § 2).
 *
 * **КАРТА КЛАВІШ ЦЬОГО ПРОЄКТУ** — щоб наступний агент не аналізував заново:
 *
 * | Клавіша | Стан | Де / чому |
 * |---|---|---|
 * | `T` | ✅ тема | `ui/ServiceLayer.svelte`; тем дві, тож клавіша перемикає, а не відкриває список |
 * | `L` | ✅ мова | там же; мов теж дві (uk, en) — те саме міркування (HK-LANGUAGE-KEY) |
 * | `B` | ✅ тло | там же; чотири типи (немає / частинки / хвилі / …) по колу через `ui.setBackgroundType` |
 * | `V` | ✅ службове табло | `ui/ServiceBadge.svelte` |
 * | `R` | ✅ аварійне скидання | `services/resetService.ts` |
 * | `Esc` | ✅ закрити меню / модалку | `MobileMenu`, `PianoModal` — кожне своє |
 * | `A S D F G H J K` + `W E T Y U O P ;` | ⚠️ ПІАНІНО, поки відкрите | `config/piano.ts` тримає 17 фізичних клавіш, `ui/PianoModal.svelte` слухає їх лише за `isOpen` |
 * | `M` | ⏭️ ПРОПУЩЕНО | глушника звуку немає: звук у проєкті лише в піаніно, і там його «вимикає» закрита модалка |
 * | `C` | ⏭️ ПРОПУЩЕНО | годинника на екрані немає |
 * | `F` (фулскрин) | ⏭️ ПРОПУЩЕНО | на весь екран немає — і `F` усе одно зайнята піаніно |
 * | `H` (на початок) | ⏭️ ПРОПУЩЕНО | те саме: зайнята піаніно; «на початок» — це лого в шапці |
 * | `PgUp`/`PgDn`, `1`–`9` | ⏭️ ПРОПУЩЕНО | сторінка не крокує секціями |
 *
 * Пропущене — це відсутня функція, а не забута клавіша. Щойно функція
 * зʼявиться, клавіша береться з канонічної карти (HOTKEYS-v8 § 1.1), а не
 * вигадується.
 *
 * `T`, `L` і `B` ВИМИКАЮТЬСЯ перемикачем «Гарячі клавіші» в налаштуваннях
 * шапки — це виконання WCAG SC 2.1.4 (HOTKEYS-v8 § 3, рівень A). Умова стоїть
 * в обробнику, а не тут: `acceptsShortcut` відповідає на питання «чи ця подія
 * взагалі наша», і воно не залежить від того, чи скорочення ввімкнені.
 *
 * Слухач жив у шапці, коли ця таблиця писалася, і переїхав у `ServiceLayer`
 * разом із таблом версії: усе, що ці клавіші перемикають, живе в `ui`, а від
 * шапки не потрібно нічого.
 *
 * ⚠️ ПІАНІНО — окремий випадок, і саме через нього тут є `keyboardCapture`
 * нижче. Віртуальне піаніно володіє 17 літерами, зокрема `T` і `L`, — але лише
 * поки його модалка відкрита. Без спільного прапорця «клавіатуру зайнято» гра на
 * ноті `F#` (клавіша `T`) міняла б заодно тему сайту, а `L` (нота `D`) — мову.
 */

/**
 * Скільки накладок наразі забрали клавіатуру собі.
 *
 * **Лічильник, а не `boolean`.** Дві накладки можуть існувати одночасно (модалка
 * поверх модалки), і тоді закриття верхньої з `boolean` віддало б клавіатуру
 * сайту, поки нижня ще відкрита.
 *
 * **Чому це не можна вирішити через `event.stopPropagation`.** Обидва обробники
 * висять на `window`, а порядок між слухачами одного вузла — це порядок
 * реєстрації, тобто порядок монтування компонентів. Він змінюється від того, з
 * якої сторінки людина прийшла.
 */
let captureCount = 0;

/**
 * Забрати клавіатуру собі. Повертає функцію, яка її віддає.
 *
 * Повертає саме функцію, а не має пари `release()`: тоді її можна віддати прямо в
 * cleanup `$effect`/`onMount`, і забути про звільнення важче.
 */
export function captureKeyboard(): () => void {
	captureCount += 1;
	let released = false;
	return () => {
		// Захист від подвійного виклику: cleanup у Svelte може прийти двічі під час
		// HMR, і лічильник пішов би в мінус — тобто клавіатура лишилася б «зайнятою»
		// назавжди.
		if (released) return;
		released = true;
		captureCount = Math.max(0, captureCount - 1);
	};
}

/** Чи зайнята клавіатура накладкою. Читають обробник шапки й тести. */
export function isKeyboardCaptured(): boolean {
	return captureCount > 0;
}

/**
 * Чи друкує людина зараз у полі.
 *
 * `closest`, а не порівняння `tagName`: у `contenteditable` фокус стоїть на
 * вкладеному вузлі, і його `tagName` — це `SPAN`, тож перевірка за тегом такий
 * випадок пропускає.
 */
export function isTypingTarget(target: EventTarget | null | undefined): boolean {
	const element = target as HTMLElement | null | undefined;
	if (!element || typeof element.closest !== 'function') return false;
	return (
		element.closest('input, textarea, select, [contenteditable]:not([contenteditable="false"])') !==
		null
	);
}

/**
 * Чи це одиночна клавіша без модифікаторів.
 *
 * `Ctrl+T` відкриває вкладку, `Ctrl+R` перезавантажує, `Ctrl+V` вставляє — і всі
 * три дають той самий `event.code`, що й одиночна клавіша. `Shift` навмисно не
 * перевіряється: він не змінює `code`, а комбінації з ним браузер зазвичай не
 * займає.
 */
export function isPlainKey(event: {
	ctrlKey?: boolean;
	metaKey?: boolean;
	altKey?: boolean;
}): boolean {
	return !event.ctrlKey && !event.metaKey && !event.altKey;
}

/**
 * Усі три захисти разом — те, що потрібно обробникові сайту.
 *
 * `Escape` тут НЕ виняток, на відміну від сусідніх проєктів, і причина конкретна:
 * поки клавіатуру зайнято, `Escape` належить тій самій накладці, що її зайняла, —
 * і кожна з них закриває себе сама. Пропустити `Escape` сюди означало б закрити
 * заодно й меню шапки під модалкою.
 */
export function acceptsShortcut(event: KeyboardEvent): boolean {
	if (isKeyboardCaptured()) return false;
	if (!isPlainKey(event)) return false;
	if (event.code === 'Escape') return true;
	return !isTypingTarget(event.target);
}
