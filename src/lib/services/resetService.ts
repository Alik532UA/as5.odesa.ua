import { STORAGE_PREFIX } from '$lib/config/storage';
import { storage } from './storage';

/**
 * Аварійне скидання: стерти локальні дані ЦЬОГО сайту й перезавантажитися.
 *
 * **Навіщо воно.** Тема, мова, тип тла й позначки бета-тесту живуть у сховищі, і
 * коли вони суперечать новій збірці, сторінка відкривається зламаною — а лікується
 * це відкриттям DevTools, чого відвідувач не зробить. Жест на клавіатурі дає той
 * самий результат без інструментів розробника.
 *
 * **Що стирається — і чому саме так, а не `localStorage.clear()`.** Канонічна
 * адреса тут ВЛАСНИЙ домен (`base: ''`), тобто origin ексклюзивний. Але запасна
 * адреса `alik532ua.github.io/as5.odesa.ua/` теж віддається, і ТАМ origin спільний
 * із сімома сусідніми проєктами (PROJECT-CONTEXT.md § базові параметри). Отже
 * `clear()` без префікса знищив би чужі дані — рідко, лише на запасній адресі, і
 * саме тому це найгірший вид помилки: він не трапляється в тестах.
 *
 * **Ніколи не кидає.** Це аварійний шлях: людина кличе його тоді, коли вже щось не
 * працює. Виняток усередині означав би «навіть скидання зламане».
 */

/** Скільком натисканням запускати жест. Різні числа — різна ціна помилки. */
export const RESET_PRESSES_DEV = 5;
/**
 * 55 у проді — те саме число, що в сусідніх проєктах.
 *
 * Число велике не для складності, а тому що ціна випадкового спрацювання — усі
 * місцеві налаштування. Плюс підтвердження: разом це два незалежні барʼєри, і
 * жоден не покладається на уважність.
 */
export const RESET_PRESSES_PROD = 55;

/**
 * Текст підтвердження свідомо НЕ через i18n.
 *
 * `confirm()` — блокуючий діалог браузера, і він може знадобитися саме тоді, коли
 * зламалося завантаження словників: тоді `$t()` віддав би ключ замість тексту,
 * тобто людина побачила б «reset.confirm» перед знищенням своїх даних. Єдине місце
 * в проєкті, де жорсткий рядок правильніший за переклад — і саме тому обидві мови
 * сайту стоять тут поруч.
 */
const CONFIRM_TEXT =
	'Це видалить локальні налаштування цього сайту: тему, мову, тип тла, позначки. Продовжити? / This clears local settings for this site. Continue?';

/**
 * @param askConfirmation питати підтвердження. У проді — обовʼязково: без нього
 * жест стирає дані без жодного запитання.
 */
export async function hardReset(askConfirmation = true): Promise<void> {
	if (typeof window === 'undefined') return;

	if (askConfirmation && !window.confirm(CONFIRM_TEXT)) return;

	/*
	 * Кожна половина — під власним `try`, а не всі разом: збій у першій не має
	 * скасовувати другу. Скидання кличуть, коли вже зламано, тож воно мусить
	 * зробити стільки, скільки зможе.
	 *
	 * Порожній `catch` тут не недогляд: повідомляти нема кому й нема куди —
	 * сторінка зараз зникне.
	 */
	try {
		// Лише префіксовані ключі — сусіди по запасній адресі не постраждають.
		storage.clear();
	} catch {
		/* сховище недоступне — решта скидання все одно потрібна */
	}

	/*
	 * КУКІ ТУТ НЕ ЧИСТЯТЬСЯ, і це рішення, а не пропуск.
	 *
	 * Сайт не ставить жодного кукі: жодного `document.cookie =` у коді немає, а
	 * аналітика підключена як `gtag.js`, чиї кукі належать домену Google, не нам.
	 * Тобто чистити нічого — але дорого. На запасній адресі
	 * `alik532ua.github.io/as5.odesa.ua/` у `document.cookie` видно кукі, поставлені
	 * з path=/, тобто СПІЛЬНІ для всього origin: обхід «видалити все, що бачу»
	 * витер би сеанси сусідніх проєктів. Прибрати чуже, не маючи свого, — не
	 * скидання, а шкода.
	 */

	await clearOwnCaches();
	await unregisterControllingWorkers();

	window.location.reload();
}

/**
 * Кеші — лише свої, за префіксом проєкту.
 *
 * `caches.keys()` віддає імена кешів усього ORIGIN. На власному домені це й так
 * лише наші, на запасній адресі — разом із кешами сусідів. Умова названа
 * префіксом, а не переліком імен: перелік розійшовся б із тим, що справді створює
 * service worker, а префікс — те саме джерело, що в ключів сховища.
 */
async function clearOwnCaches(): Promise<void> {
	if (!('caches' in window)) return;
	try {
		const names = await caches.keys();
		await Promise.all(
			names.filter((name) => name.startsWith(STORAGE_PREFIX)).map((name) => caches.delete(name))
		);
	} catch {
		/* Cache API недоступний або заблокований */
	}
}

/**
 * Реєстрації service worker — лише ті, що керують ЦІЄЮ сторінкою.
 *
 * **Чому не за `base`, як у сусідніх проєктах.** У них `base` — це `/VetCrewGames`
 * чи `/MindStep`, тобто сама назва відрізняє свій scope від чужого. Тут `base`
 * порожній (власний домен), і фільтр за ним на запасній адресі
 * `alik532ua.github.io/as5.odesa.ua/` пропустив би ВСІ реєстрації origin — тобто
 * рівно те, що фільтр мав спинити.
 *
 * Тому умова інша й не залежить від `base` взагалі: scope service worker завжди є
 * префіксом адрес, якими він керує. Отже «керує цією сторінкою» = адреса сторінки
 * починається зі scope. Сусідній `/MindStep/` цієї перевірки не проходить, а
 * власний — проходить на обох адресах.
 *
 * Service worker у проєкті ще немає (ні `vite-plugin-pwa`, ні свого файла), тож
 * сьогодні ця половина не робить нічого. Написати її ПІСЛЯ появи PWA означало б
 * написати її в поспіху — а саме тут поспіх коштує чужих даних.
 */
async function unregisterControllingWorkers(): Promise<void> {
	if (!('serviceWorker' in navigator)) return;
	try {
		const registrations = await navigator.serviceWorker.getRegistrations();
		const here = window.location.href;
		await Promise.all(
			registrations
				.filter((registration) => here.startsWith(registration.scope))
				.map((registration) => registration.unregister())
		);
	} catch {
		/* реєстрації недоступні — решта скидання вже виконана */
	}
}
