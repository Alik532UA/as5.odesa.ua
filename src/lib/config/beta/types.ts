/**
 * Чеклист бета-тестування як ДАНІ (BETA-CHECKLIST-v8).
 *
 * ## Навіщо це тут, якщо перевірок 102
 *
 * Половину роботи машина не робить і не зробить: чи натискається кнопка
 * пальцем, чи не блимає тема, чи чути звук піаніно, чи не поїхала розкладка на
 * чужому телефоні. У цього проєкту цей залишок навіть перелічений — сім рядків
 * у PROJECT-CONTEXT.md під заголовком «Що не перевіряється автоматично», і
 * план у половини з них — «код-рев'ю» або «ручна перевірка перед релізом».
 * Тобто робить її той, хто згадає, і в обсязі, який згадає.
 *
 * Цей файл дає їй власника: список пунктів, які можна віддати людині.
 *
 * ## Чому дані, а не `QA.md`
 *
 * Текстовий чеклист ніхто не звіряє з кодом. Він застаріває мовчки й починає
 * казати «перевірено» про те, чого вже немає — у джерелі канону такий пункт
 * прожив 46 комітів. Тут кожне поле нижче має інваріант у
 * `src/beta-checklist.test.ts`, і найдорожчий із них — `testid`: пункт, що
 * просить щось натиснути, зобов'язаний назвати локатор, який справді є в
 * розмітці.
 */

/**
 * Обидві мови в ОДНОМУ об'єкті, а не двома деревами файлів. Відповідність
 * вимагає ТИП: пункт без англійського тексту просто не збереться, і окреме
 * правило «однакова кількість пунктів у двох мовах» не потрібне.
 *
 * Тексти пунктів НЕ живуть у словнику інтерфейсу (`i18n/locales/*.json`)
 * навмисно: їх десятки, вони змінюються іншим циклом, і паритет словників
 * зробив би кожну правку подвійною роботою в чужому файлі.
 */
export interface Localized {
	uk: string;
	en: string;
}

/**
 * Чи може цей пункт перевірити машина.
 *
 * Рівень визначається тим, що тест СПРАВДІ доводить, а не темою. `contrast.test.ts`
 * доводить, що пари токенів проходять WCAG; він не доводить, що жоден напис не
 * зник на напівпрозорому тлі — це різні твердження, і другий пункт лишається
 * `testable`.
 */
export type Coverage =
	/** Око, палець, вухо, справжній телефон. Машині недоступне. */
	| 'manual'
	/** Покрити можна, покриття немає. Це беклог тестів із назвами. */
	| 'testable'
	/** Покрито; файл названий і мусить існувати. Контрольна група. */
	| 'covered';

export interface BetaCheck {
	/**
	 * Стабільний НАЗАВЖДИ: це ключ прогресу в сховищі. Перейменувати
	 * `common_7` означає стерти людині позначку. Нові пункти дописуються з
	 * новим номером; перенумеровувати наявні не можна навіть тоді, коли
	 * порядок змінився.
	 */
	id: string;
	/** Вкладка, якій пункт належить. */
	tab: BetaTabId;
	/** Текст для людини: дія та її ВИДИМИЙ або чутний наслідок. */
	text: Localized;
	coverage: Coverage;
	/** Обов'язковий для `covered`, заборонений для решти. Файл мусить існувати. */
	test?: string;
	/** Обов'язковий там, де в тексті є «натисніть». Мусить бути в розмітці. */
	testid?: string;
	/** Перевірка МЕЖІ: «не мусить». Найдорожчі дефекти тихі. */
	negative?: true;
}

export type BetaTabId = 'common' | 'home' | 'pages';

/**
 * Маршрути сайту, які вкладка може заявити. Це не окремий список «на око»:
 * інваріант § 5.1 звіряє його з реальними теками в `src/routes`, тож нова
 * сторінка або потрапляє під чиюсь вкладку, або йде у виняток нижче — мовчки
 * лишитися без перевірок вона не може.
 */
export type BetaRoute = '/' | '/about' | '/history' | '/competitions' | '/admission';

export interface BetaTab {
	id: BetaTabId;
	title: Localized;
	/** Маршрути, за які вкладка відповідає. Порожньо — наскрізна вкладка. */
	routes: readonly BetaRoute[];
}

