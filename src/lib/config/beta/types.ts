/**
 * Порядок показу рівнів, і це не косметика:
 *
 *  - `manual` перший, бо людина витрачається спершу там, де машини немає;
 *  - `testable` посередині — це готовий беклог тестів;
 *  - `covered` лишається в списку як КОНТРОЛЬНА ГРУПА. Помилка, знайдена в
 *    покритому місці, — звіт про дефект ТЕСТА, а не сайту, і вона знецінює всі
 *    зелені прогони. У звіті така помилка отримує окремий рядок.
 */
export const COVERAGE_ORDER: readonly Coverage[] = ['manual', 'testable', 'covered'];

/** Чотири стани відповіді. `unset` — не перевірено. */
export type Vote = 'fail' | 'weird' | 'ok';

/**
 * Позначка несе версію збірки.
 *
 * Без цього список поступово стає звітом про минуле, який читають як звіт про
 * теперішнє: галочка «працює» з-перед сорока комітів виглядає точно так само,
 * як сьогоднішня. Позначка з іншої версії не зникає — вона все ще щось
 * означає, — але підписується й не рахується в поступі.
 */
export interface Mark {
	vote: Vote;
	version: string;
}
