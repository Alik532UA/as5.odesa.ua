/**
 * Переклад із запасним текстом (I18N-v8 § 2, ERROR-HANDLING-v8 § 4.3).
 *
 * `svelte-i18n` вантажить словники асинхронно, і доки словник не приїхав, `$t`
 * повертає **сам ключ**. Показати відвідувачу `error.generic.title` не можна —
 * тому кожен рядок, який може бути показаний до завантаження словника, іде
 * через цю функцію.
 *
 * Місць, де це потрібно, три, і всі три — саме ті, де словника може ще не бути:
 * `+layout.svelte` (мета-теги під час prerender), `+error.svelte` (сторінка
 * помилки, зокрема 404 із `404.html`) та межа помилок. Доти кожне з них мало
 * власну копію цієї функції; копії розходяться мовчки, а перевірити, що всі три
 * поводяться однаково, було нічим.
 *
 * Функція приймає `$t` аргументом, а не читає стор сама: читання `$t` у
 * компоненті лишає значення реактивним, тож рядки перемальовуються, коли
 * словник нарешті приїхав або коли користувач перемкнув мову. `get(t)` усередині
 * зробив би їх одноразовими.
 */
export function safeT(translate: (key: string) => string, key: string, fallback: string): string {
	try {
		const result = translate(key);
		// `$t` віддає ключ, коли перекладу немає — це не переклад, а його адреса.
		return result && result !== key ? result : fallback;
	} catch {
		// Кидає, доки `init()` не виконався. Для показу це те саме, що «немає
		// перекладу», і окремої гілки не потребує.
		return fallback;
	}
}
