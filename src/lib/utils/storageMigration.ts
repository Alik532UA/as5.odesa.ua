import { STORAGE_PREFIX } from '$lib/config/storage';
import { storage } from '$lib/services/storage';

// Реекспорт: префікс переїхав у `$lib/config/storage`, поряд із `getStorageKey`.
// Місце для константи конфігурації — конфіг, а не утиліта міграції.
export { STORAGE_PREFIX };

const LEGACY_KEYS = ['theme', 'backgroundType', 'enableDynamicBackground', 'enableBlurEffect', 'lang'];

/**
 * Позначка «міграцію вже виконано» — через фасад, тобто з префіксом проєкту.
 *
 * Її бракувало, і це не оптимізація (STORAGE-NAMESPACE-v9 § Крок 4 має її в
 * зразку першим рядком). Без позначки міграція виконується на КОЖНОМУ
 * завантаженні сторінки — назавжди, — а не один раз після переїзду на префікси.
 *
 * Ціна на спільному origin конкретна, і умова `новий ключ ще порожній` від неї
 * не рятує. Ключі `theme`, `lang`, `backgroundType`, `enableBlurEffect`,
 * `enableDynamicBackground` — БЕЗ префікса, тобто нічиї: саме тому реєстр
 * префіксів і з'явився. Наш префіксований ключ при цьому у більшості
 * відвідувачів ПОРОЖНІЙ — він пишеться лише тоді, коли людина сама щось обрала
 * (тема з системи не рахується вибором, `ui.svelte.ts`). Отже сусідній
 * застосунок на `alik532ua.github.io`, який ще не переїхав на префікси, пише
 * `theme` без префікса — а наступний захід на нашу сторінку за запасною адресою
 * копіює це значення собі й ВИДАЛЯЄ чуже.
 *
 * Із позначкою вікно, у якому це можливо, — рівно один захід одного браузера
 * замість усіх заходів назавжди.
 */
const DONE_KEY = '__migrated';

/**
 * Переносить ключі без префікса під префікс проєкту. Викликається на старті.
 *
 * Видалення старого ключа лишається (§ Крок 4 називає це прямо: інакше він
 * лежить далі й наступна міграція знайде його знову), але тепер разом із
 * позначкою — тобто один раз, а не щоразу.
 */
export function migrateStorageKeys() {
	if (typeof window === 'undefined') return;
	// Фасад сам не кидає: у приватному режимі й у чужому iframe він віддає null.
	if (storage.get(DONE_KEY) !== null) return;

	// Єдине місце, якому фасад `$lib/services/storage` не підходить: міграція
	// читає ключі БЕЗ префікса, а фасад префікс додає завжди — на те він і є.
	// Тому тут прямий доступ, але обгорнутий: у приватному режимі й у чужому
	// iframe кидає вже сам `localStorage`, а міграція виконується на старті —
	// тобто виняток звідси поклав би сайт цілком.
	try {
		for (const key of LEGACY_KEYS) {
			const oldValue = localStorage.getItem(key);
			const newKey = STORAGE_PREFIX + key;

			// Переносимо, лише якщо старе значення є, а нового ще немає.
			if (oldValue !== null && localStorage.getItem(newKey) === null) {
				localStorage.setItem(newKey, oldValue);
				// Origin спільний, тому старий ключ без префікса прибираємо:
				// інакше він лишається пасткою для сусіднього проєкту.
				localStorage.removeItem(key);
			}
		}
	} catch (e) {
		console.warn('[storageMigration] сховище недоступне — міграцію пропущено', e);
		// Позначка НЕ ставиться: сховище відмовило, міграція не виконана, і
		// наступний захід має спробувати ще раз. Інакше дані лишилися б під
		// старими ключами назавжди.
		return;
	}

	storage.set(DONE_KEY, 'true');
}
